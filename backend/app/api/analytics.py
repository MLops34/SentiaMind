router = APIRouter(prefix="/analytics", tags=["Analytics"])


@router.get(
    "/summary",
    response_model=EmotionSummary,
    summary="Get aggregated emotional summary over a time period",
)
async def get_emotion_summary(
    days: int = Query(7, ge=1, le=365),
    current_user: User = Depends(get_current_active_user),
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Compute average emotional metrics and highlight high-stress days."""
    cutoff = datetime.now(timezone.utc) - timedelta(days=days)

    stmt = (
        select(EmotionScore)
        .where(
            EmotionScore.user_id == current_user.id,
            EmotionScore.scored_at >= cutoff,
        )
        .order_by(EmotionScore.scored_at.asc())
    )
    records = (await db.execute(stmt)).scalars().all()
    total_entries = len(records)

    if total_entries == 0:
        # Default empty summary
        default_scores = EmotionScores(
            joy=0.0,
            sadness=0.0,
            anxiety=0.0,
            anger=0.0,
            fear=0.0,
            dominant_emotion="neutral",
            model_confidence=0.0,
        )
        return EmotionSummary(
            period_days=days,
            average_scores=default_scores,
            dominant_emotion_overall="neutral",
            total_entries=0,
            journaling_streak_days=0,
            highest_stress_day=None,
            highest_stress_score=None,
        )

    # Compute averages
    avg_joy = round(sum(r.joy for r in records) / total_entries, 3)
    avg_sadness = round(sum(r.sadness for r in records) / total_entries, 3)
    avg_anxiety = round(sum(r.anxiety for r in records) / total_entries, 3)
    avg_anger = round(sum(r.anger for r in records) / total_entries, 3)
    avg_fear = round(sum(r.fear for r in records) / total_entries, 3)

    avg_map = {
        "joy": avg_joy,
        "sadness": avg_sadness,
        "anxiety": avg_anxiety,
        "anger": avg_anger,
        "fear": avg_fear,
    }
    dominant_overall = max(avg_map, key=avg_map.get)

    avg_scores = EmotionScores(
        joy=avg_joy,
        sadness=avg_sadness,
        anxiety=avg_anxiety,
        anger=avg_anger,
        fear=avg_fear,
        dominant_emotion=dominant_overall,
        model_confidence=float(avg_map[dominant_overall]),
    )

    # Group by date to find highest stress day
    daily_scores: dict[date, list[EmotionScore]] = defaultdict(list)
    for r in records:
        daily_scores[r.scored_at.date()].append(r)

    highest_stress_day: date | None = None
    highest_stress_score: float = -1.0

    for d, day_records in daily_scores.items():
        day_stress = sum((r.anxiety * 1.3 + r.sadness * 0.7 + r.fear * 0.7) for r in day_records) / len(day_records)
        if day_stress > highest_stress_score:
            highest_stress_score = round(day_stress, 3)
            highest_stress_day = d

    # Calculate current streak
    streak_data = await calculate_user_streak(current_user.id, db)

    return EmotionSummary(
        period_days=days,
        average_scores=avg_scores,
        dominant_emotion_overall=dominant_overall,
        total_entries=total_entries,
        journaling_streak_days=streak_data["current_streak"],
        highest_stress_day=highest_stress_day,
        highest_stress_score=highest_stress_score if highest_stress_score >= 0 else None,
    )


@router.get(
    "/forecast",
    response_model=ForecastResponse,
    summary="Generate 7-day predictive stress forecast",
)
async def get_forecast(
    current_user: User = Depends(get_current_active_user),
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Predictive stress forecast generated by the LSTM/WMA engine."""
    stmt = (
        select(EmotionScore)
        .where(EmotionScore.user_id == current_user.id)
        .order_by(EmotionScore.scored_at.asc())
        .limit(60)
    )
    records = (await db.execute(stmt)).scalars().all()
    return stress_forecaster.forecast(records)


@router.get(
    "/streak",
    response_model=StreakResponse,
    summary="Get user's journaling streak statistics",
)
async def get_streak(
    current_user: User = Depends(get_current_active_user),
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Retrieve consecutive active days and total journaling activity."""
    streak_info = await calculate_user_streak(current_user.id, db)
    return StreakResponse(
        current_streak_days=streak_info["current_streak"],
        longest_streak_days=streak_info["longest_streak"],
        total_entries=streak_info["total_entries"],
        first_entry_date=streak_info["first_entry_date"],
        last_entry_date=streak_info["last_entry_date"],
    )


@router.get(
    "/trends",
    response_model=List[EmotionTrendPoint],
    summary="Get daily emotion trend points for charts",
)
async def get_trends(
    days: int = Query(14, ge=1, le=90),
    current_user: User = Depends(get_current_active_user),
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Return day-by-day emotional trajectory over specified time window."""
    today = datetime.now(timezone.utc).date()
    cutoff = datetime.now(timezone.utc) - timedelta(days=days)

    stmt = (
        select(EmotionScore)
        .where(
            EmotionScore.user_id == current_user.id,
            EmotionScore.scored_at >= cutoff,
        )
        .order_by(EmotionScore.scored_at.asc())
    )
    records = (await db.execute(stmt)).scalars().all()

    daily_map: dict[date, list[EmotionScore]] = defaultdict(list)
    for r in records:
        daily_map[r.scored_at.date()].append(r)

    trend_points: List[EmotionTrendPoint] = []
    # Fill in all days in range for continuous charts
    for i in range(days):
        cur_date = today - timedelta(days=(days - 1 - i))
        day_recs = daily_map.get(cur_date, [])

        if day_recs:
            count = len(day_recs)
            trend_points.append(
                EmotionTrendPoint(
                    date=cur_date,
                    joy=round(sum(r.joy for r in day_recs) / count, 3),
                    sadness=round(sum(r.sadness for r in day_recs) / count, 3),
                    anxiety=round(sum(r.anxiety for r in day_recs) / count, 3),
                    anger=round(sum(r.anger for r in day_recs) / count, 3),
                    fear=round(sum(r.fear for r in day_recs) / count, 3),
                    entry_count=count,
                )
            )
        else:
            trend_points.append(
                EmotionTrendPoint(
                    date=cur_date,
                    joy=0.0,
                    sadness=0.0,
                    anxiety=0.0,
                    anger=0.0,
                    fear=0.0,
                    entry_count=0,
                )
            )

    return trend_points


async def calculate_user_streak(user_id: Any, db: AsyncSession) -> dict:
    """Helper to compute current streak, max streak, and date boundaries."""
    stmt = (
        select(Journal.created_at)
        .where(Journal.user_id == user_id)
        .order_by(Journal.created_at.asc())
    )
    timestamps = (await db.execute(stmt)).scalars().all()

    if not timestamps:
        return {
            "current_streak": 0,
            "longest_streak": 0,
            "total_entries": 0,
            "first_entry_date": None,
            "last_entry_date": None,
        }

    distinct_dates = sorted({t.date() for t in timestamps})
    first_date = distinct_dates[0]
    last_date = distinct_dates[-1]

    # Calculate streaks
    longest_streak = 1
    current_streak = 0
    temp_streak = 1

    for i in range(1, len(distinct_dates)):
        if distinct_dates[i] - distinct_dates[i - 1] == timedelta(days=1):
            temp_streak += 1
            if temp_streak > longest_streak:
                longest_streak = temp_streak
        else:
            temp_streak = 1

    today = datetime.now(timezone.utc).date()
    yesterday = today - timedelta(days=1)

    # Current streak counts if last entry was today or yesterday
    if last_date in (today, yesterday):
        current_streak = 1
        curr = last_date
        date_set = set(distinct_dates)
        while (curr - timedelta(days=1)) in date_set:
            current_streak += 1
            curr -= timedelta(days=1)

    return {
        "current_streak": current_streak,
        "longest_streak": longest_streak,
        "total_entries": len(timestamps),
        "first_entry_date": first_date,
        "last_entry_date": last_date,
    }
